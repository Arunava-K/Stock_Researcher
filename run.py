def _parse_args() -> "argparse.Namespace":
    import argparse
    p = argparse.ArgumentParser(description="Daily stock research routine")
    p.add_argument(
        "--prior-state",
        type=Path,
        default=None,
        help="Path to JSON file with prior state (history). When omitted, "
             "falls back to data/state.json if it exists, else fresh start.",
    )
    p.add_argument(
        "--state-out",
        type=Path,
        default=None,
        help="Where to write the new state JSON. When omitted, writes to "
             "data/state.json so local re-runs accumulate history.",
    )
    return p.parse_args()


def _load_state(path: Path | None) -> dict | None:
    """Load state from path. None if file missing. Falls back to local default
    when the explicit path is None."""
    if path is None:
        path = DEFAULT_LOCAL_STATE_PATH
    if not path.exists():
        return None
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError) as e:
        print(f"WARN: could not parse state at {path}: {e}", file=sys.stderr)
        return None


def _write_state(path: Path | None, state: dict) -> Path:
    if path is None:
        path = DEFAULT_LOCAL_STATE_PATH
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(state, indent=2), encoding="utf-8")
    return path


def main() -> int:
    args = _parse_args()
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    warnings: list[str] = []

    prior_state = _load_state(args.prior_state)

    # 1. Fetch bhavcopy (authoritative latest close)
    bhav_df = None
    bhav_date = None
    try:
        print("fetching NSE bhavcopy ...")
        bhav_df, bhav_date = fetch_latest_bhavcopy()
        print(f"  bhavcopy date: {bhav_date}")
    except Exception as e:
        warnings.append(
            f"NSE bhavcopy unreachable ({e}). "
            f"Latest close falls back to Yahoo and may be lagged by ≥1 trading day."
        )
        print(f"  [bhavcopy-error] {e}", file=sys.stderr)

    # 2. Load universe (held positions + picked names)
    universe = load_universe()
    print(f"universe size: {len(universe)} ({sum(1 for u in universe if u.get('held'))} held + {sum(1 for u in universe if not u.get('held'))} picked)")

    # 3. Per-ticker: yfinance history + splice bhavcopy row if newer
    rows: list[dict] = []
    failures: list[str] = []
    # Keep OHLC frames around so the trade-plan generator can compute ATR /
    # swing levels later without re-fetching.
    ohlc_by_symbol: dict[str, "pd.DataFrame"] = {}

    for i, entry in enumerate(universe, 1):
        ticker = entry["ticker"]
        print(f"  [{i:>2}/{len(universe)}] {entry['symbol']:<14} ...", end=" ", flush=True)
        yf_df = fetch_yf_history(ticker)
        if yf_df is None:
            failures.append(ticker)
            print("FAILED")
            continue

        source_label = "yfinance"
        if bhav_df is not None:
            bhav_row = lookup_eq(bhav_df, entry["symbol"])
            if bhav_row is not None:
                merged = merge_bhav_into_history(yf_df, bhav_row, bhav_date)
                if len(merged) > len(yf_df):
                    source_label = "bhavcopy"
                yf_df = merged
            else:
                warnings.append(f"{entry['symbol']} not found in bhavcopy — using yfinance")

        rows.append(score_one(entry, yf_df, source_label))
        ohlc_by_symbol[entry["symbol"]] = yf_df
        print("ok")

    # 4. Fetch Screener.in fundamentals for every row (~30s with politeness sleep)
    if rows:
        symbols = [r["symbol"] for r in rows]
        print(f"\nfetching Screener.in fundamentals for {len(symbols)} tickers ...")

        def _progress(i, total, sym, result):
            tag = "ok" if result else "miss"
            print(f"  [{i:>2}/{total}] {sym:<14} ... {tag}")

        fund_map = fetch_fundamentals_many(symbols, on_progress=_progress)
        miss_count = sum(1 for v in fund_map.values() if v is None)
        if miss_count:
            warnings.append(
                f"Screener.in scrape failed for {miss_count}/{len(symbols)} tickers — those bypass fundamentals gates"
            )

        # Annotate each row with fundamentals + gate result
        for r in rows:
            fund = fund_map.get(r["symbol"])
            r["fundamentals"] = fund
            passes, reason = evaluate_fundamentals_gates(fund)
            r["passes_gates"] = passes
            r["gate_reason"] = reason

    # 5. Trajectory annotation — compare today's snapshot to prior_state
    if rows and bhav_date is not None:
        annotate_trajectory(rows, bhav_date.isoformat(), FLAG_THRESHOLD, prior_state)
    else:
        for r in rows:
            r["prev_score"] = None
            r["score_delta"] = None
            r["streak_days"] = 0
            r["trajectory_tag"] = None

    # 5b. Setup-status classification + trade-plan generation. Trade plans only
    #     get computed for FORMING / READY / TRIGGERED / STALE since these are
    #     the only statuses where a plan or watch list adds value.
    for r in rows:
        status = classify_status(r, FLAG_THRESHOLD)
        r["setup_status"] = status
        r["watch_conditions"] = None
        r["trade_plan"] = None

        if status in ("READY", "TRIGGERED"):
            df = ohlc_by_symbol.get(r["symbol"])
            r["trade_plan"] = compute_trade_plan(r, df) if df is not None else None
        elif status == "FORMING":
            r["watch_conditions"] = watch_conditions(r)

    # 6. Recent corporate announcements — only for "candidates of interest":
    #    anything not in the WATCHING bucket (held + ready + triggered + forming + stale).
    #    Pure watching list is too noisy to deep-dive.
    of_interest = [
        r for r in rows
        if r["held"] or r.get("setup_status") in ("READY", "TRIGGERED", "FORMING", "STALE")
    ]
    if of_interest:
        print(f"\nfetching announcements for {len(of_interest)} candidate{'s' if len(of_interest)!=1 else ''} of interest ...")
        for r in of_interest:
            anns = fetch_announcements(r["symbol"], days=30)
            if anns is None:
                warnings.append(f"announcements fetch failed for {r['symbol']}")
                r["announcements"] = None
                r["announcements_attempted"] = True
                print(f"  {r['symbol']:<14} ... FAILED")
            else:
                r["announcements"] = anns
                r["announcements_attempted"] = True
                print(f"  {r['symbol']:<14} ... {len(anns)} in last 30d")
    for r in rows:
        r.setdefault("announcements", None)
        r.setdefault("announcements_attempted", False)

    if not rows:
        print("FATAL: no data fetched for any ticker", file=sys.stderr)
        return 1

    # 3. Render
    if bhav_date is not None:
        latest_dates = {r["as_of"] for r in rows}
        if len(latest_dates) == 1:
            freshness = f"{latest_dates.pop()} (NSE bhavcopy)"
        else:
            freshness = f"mixed — bhavcopy {bhav_date.isoformat()}, some tickers fell back to yfinance"
    else:
        # all yfinance
        latest_dates = sorted({r["as_of"] for r in rows})
        freshness = f"{latest_dates[-1]} (Yahoo, bhavcopy unreachable)"

    run_date = datetime.now(IST).date().isoformat()
    brief_md = render_brief(rows, run_date, freshness, warnings)

    if failures:
        brief_md += f"\n\n> **Data fetch failed for:** {', '.join(failures)}\n"

    out_md = OUTPUT_DIR / f"{run_date}.md"
    out_md.write_text(brief_md, encoding="utf-8")
    print(f"\nwrote {out_md}")

    # Build the new state and write it out for the Routine to upload to Notion
    # (or for the next local run to consume).
    if bhav_date is not None and rows:
        new_state = build_new_state(rows, bhav_date.isoformat(), prior_state)
        state_path = _write_state(args.state_out, new_state)
        print(f"wrote new state ({len(new_state['history'])} day(s) of history) → {state_path}")

    # JSON sidecar — structured data the Routine prompt reads to publish to Notion.
    sorted_rows = sorted(rows, key=lambda r: (-r["score"], r["dist_52w_high"]))
    # Flagged = clears BOTH the technical score AND the fundamentals gates.
    # Filtered out = scored well but failed fundamentals (visible separately, not hidden).
    by_status_non_held = {"READY": 0, "TRIGGERED": 0, "FORMING": 0, "STALE": 0, "WATCHING": 0}
    for r in sorted_rows:
        if r["held"]:
            continue
        s = r.get("setup_status", "WATCHING")
        by_status_non_held[s] = by_status_non_held.get(s, 0) + 1

    flagged_count = sum(
        1 for r in sorted_rows
        if r["score"] >= FLAG_THRESHOLD and r.get("passes_gates", True) and not r["held"]
    )
    filtered_out_count = sum(
        1 for r in sorted_rows
        if r["score"] >= FLAG_THRESHOLD and not r.get("passes_gates", True) and not r["held"]
    )
    watching_count = sum(1 for r in sorted_rows if r["score"] < FLAG_THRESHOLD and not r["held"])
    held_count = sum(1 for r in sorted_rows if r["held"])
    top_score = max((r["score"] for r in sorted_rows if not r["held"]), default=0)
    new_entrants_count = sum(1 for r in sorted_rows if r.get("trajectory_tag") == "NEW" and not r["held"])
    strengthening_count = sum(1 for r in sorted_rows if r.get("trajectory_tag") == "STRONGER" and not r["held"])

    if failures and not rows:
        status = "Failed"
    elif warnings or failures:
        status = "Warnings"
    else:
        status = "OK"

    sidecar = {
        "run_date": run_date,
        "freshness": freshness,
        "bhavcopy_date": bhav_date.isoformat() if bhav_date else None,
        "warnings": warnings,
        "rows": sorted_rows,
        "failures": failures,
        "aggregates": {
            "flagged_count": flagged_count,
            "filtered_out_count": filtered_out_count,
            "watching_count": watching_count,
            "held_count": held_count,
            "new_entrants_count": new_entrants_count,
            "strengthening_count": strengthening_count,
            "top_score": top_score,
            "universe_size": len(rows) + len(failures),
            "status": status,
            "by_setup_status": by_status_non_held,
        },
        "risk_config": {
            "swing_capital_inr": config.SWING_CAPITAL_INR,
            "max_concurrent_positions": config.MAX_CONCURRENT_POSITIONS,
            "max_risk_per_trade_frac": config.MAX_RISK_PER_TRADE_FRAC,
            "min_risk_reward_ratio": config.MIN_RISK_REWARD_RATIO,
            "per_slot_budget_inr": config.PER_SLOT_BUDGET_INR,
        },
    }
    out_json = OUTPUT_DIR / f"{run_date}.json"
    out_json.write_text(json.dumps(sidecar, indent=2), encoding="utf-8")
    print(f"wrote {out_json}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
