"""
v0 — universe-driven scan with 4 technical signals, fundamentals gates,
     and trajectory tracking via JSON state files.

Loads universe.json (generated by universe.py) and merges in HELD positions.
Latest close from NSE bhavcopy. Historical bars from yfinance.
Fundamentals (D/E, TTM sales growth) from Screener.in.

Signals (each contributes 1 point, score 0-4):
  1. Within 10% of 52w high (consolidation near top)
  2. MACD bullish crossover within last 5 sessions
  3. 50DMA above 200DMA (bullish trend confirmed)
  4. Latest volume >= 1.5x 20-day average (accumulation)

Flag threshold: score >= 3 AND must-pass fundamentals (D/E < 1.5, sales growth TTM > 0).
Stocks scoring high but failing fundamentals show in a "Filtered out" section.

Trajectory tags compare today's snapshot to the most recent prior snapshot:
  - 🆕 NEW       — newly cleared the flag bar today
  - 📈 STRONGER  — score rose vs prior run
  - 📉 WEAKER    — score fell vs prior run
  - 🔥 STREAK    — N consecutive days at score >= threshold

State (prior history) is read from --prior-state JSON file and written to
--state-out JSON file. The cloud Routine round-trips these via the Notion
"Routine State" page. When run locally without those flags, trajectory is
computed from a local file `data/state.json` (created on first run).
"""

