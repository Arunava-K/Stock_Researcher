NEAR_HIGH_THRESHOLD = 0.10   # within 10% of 52w high
CROSSOVER_LOOKBACK_DAYS = 5
VOLUME_ACCUM_MULTIPLE = 1.5  # latest volume vs 20d avg
FLAG_THRESHOLD = 3           # score must be >= this (out of 4) to land in "Flagged"
MAX_SCORE = 4

# Must-pass fundamentals gates. Stocks scoring above the technical threshold
# but failing these gates show in a "Filtered out" section instead of "Flagged".
MAX_DEBT_TO_EQUITY = 1.5
MIN_SALES_GROWTH_TTM_PCT = 0.0

OUTPUT_DIR = Path(__file__).parent / "briefs"
UNIVERSE_PATH = Path(__file__).parent / "universe.json"
DEFAULT_LOCAL_STATE_PATH = Path(__file__).parent / "data" / "state.json"
IST = timezone(timedelta(hours=5, minutes=30))


def load_universe() -> list[dict]:
    """Load picked universe and merge in held positions (held wins on dedup)."""
    if not UNIVERSE_PATH.exists():
        print(f"WARN: {UNIVERSE_PATH.name} not found — falling back to held positions only", file=sys.stderr)
        return list(HELD_POSITIONS)

    with UNIVERSE_PATH.open() as f:
        data = json.load(f)

    held_tickers = {h["ticker"] for h in HELD_POSITIONS}
    picked = [
        {**u, "held": False}
        for u in data["universe"]
        if u["ticker"] not in held_tickers
    ]
    return list(HELD_POSITIONS) + picked


# --- indicators -------------------------------------------------------------

def macd(close: pd.Series, fast: int = 12, slow: int = 26, signal: int = 9):
    ema_fast = close.ewm(span=fast, adjust=False).mean()
    ema_slow = close.ewm(span=slow, adjust=False).mean()
    macd_line = ema_fast - ema_slow
    signal_line = macd_line.ewm(span=signal, adjust=False).mean()
    return macd_line, signal_line


def macd_recently_crossed_up(macd_line: pd.Series, signal_line: pd.Series,
                              lookback: int = CROSSOVER_LOOKBACK_DAYS) -> bool:
    if len(macd_line) < lookback + 1:
        return False
    diff = (macd_line - signal_line).tail(lookback + 1)
    for prev, curr in zip(diff.iloc[:-1], diff.iloc[1:]):
        if prev <= 0 < curr:
            return True
    return False


def distance_from_52w_high(close: pd.Series) -> float:
    high = close.tail(252).max()
    last = close.iloc[-1]
    return float((high - last) / high)


def fifty_above_two_hundred_dma(close: pd.Series) -> tuple[bool, float | None]:
    """50-day SMA above 200-day SMA — bullish trend regime.

    Returns (signal, ratio). ratio = 50DMA / 200DMA; >1 means 50 above 200.
    Returns (False, None) when there's not enough history to compute 200DMA.
    """
    if len(close) < 200:
        return False, None
    dma_50 = float(close.tail(50).mean())
    dma_200 = float(close.tail(200).mean())
    if dma_200 == 0:
        return False, None
    ratio = dma_50 / dma_200
    return ratio > 1.0, ratio


def volume_accumulation(volume: pd.Series, multiple: float = VOLUME_ACCUM_MULTIPLE) -> tuple[bool, float | None]:
    """Latest session's volume vs the 20-day moving average preceding it.

    Returns (signal, ratio). ratio = latest_volume / mean(prior 20d).
    Returns (False, None) when insufficient history or zero baseline.
    """
    if len(volume) < 21:
        return False, None
    last_vol = float(volume.iloc[-1])
    avg_20 = float(volume.iloc[-21:-1].mean())
    if avg_20 <= 0:
        return False, None
    ratio = last_vol / avg_20
    return ratio >= multiple, ratio


def evaluate_fundamentals_gates(fund: dict | None) -> tuple[bool, str | None]:
    """
    Returns (passes, reason_if_failed).

    Conservative on missing data: if fund is None (scrape failed entirely) we
    return passes=True with a reason note — we don't punish stocks for our
    scraper being blind. The brief surfaces "no Screener data" so the user knows.

    A None on individual fields is also treated as pass-with-note for that field.
    """
    if fund is None:
        return True, "no Screener data — gates skipped"

    de = fund.get("debt_to_equity")
    sg = fund.get("sales_growth_ttm_pct")

    if de is not None and de >= MAX_DEBT_TO_EQUITY:
        return False, f"D/E {de:.2f} ≥ {MAX_DEBT_TO_EQUITY}"
    if sg is not None and sg <= MIN_SALES_GROWTH_TTM_PCT:
        return False, f"sales growth TTM {sg:+.0f}% ≤ {MIN_SALES_GROWTH_TTM_PCT:.0f}%"

    missing = []
    if de is None:
        missing.append("D/E")
    if sg is None:
        missing.append("sales growth")
    if missing:
        return True, f"partial Screener data — missing {', '.join(missing)}"

    return True, None


# --- data fetch -------------------------------------------------------------

def fetch_yf_history(ticker: str) -> pd.DataFrame | None:
    """Fetch 1y of daily OHLCV from yfinance. Drops phantom NaN rows."""
    try:
        df = yf.Ticker(ticker).history(period="1y", auto_adjust=True)
    except Exception as e:
        print(f"  [yf-error] {ticker}: {e}", file=sys.stderr)
        return None
    if df.empty:
        return None
    df = df.dropna(subset=["Close"])
    return df if not df.empty else None


def merge_bhav_into_history(yf_df: pd.DataFrame, bhav_row: dict, bhav_date: _date) -> pd.DataFrame:
    """
    Append the bhavcopy EOD bar to the yfinance history if it's newer.
    yfinance index is tz-aware (Asia/Kolkata); align the new row to that tz.
    """
    latest_yf_date = yf_df.index[-1].date()
    if bhav_date <= latest_yf_date:
        return yf_df  # yfinance already caught up — no need to splice

    tz = yf_df.index.tz
    new_idx = pd.Timestamp(bhav_date, tz=tz) if tz is not None else pd.Timestamp(bhav_date)
    new_row = pd.DataFrame(
        {
            "Open":   [bhav_row["open"]],
            "High":   [bhav_row["high"]],
            "Low":    [bhav_row["low"]],
            "Close":  [bhav_row["close"]],
            "Volume": [bhav_row["volume"]],
        },
        index=[new_idx],
    )
    return pd.concat([yf_df, new_row])


# --- scoring + brief --------------------------------------------------------

def score_one(entry: dict, df: pd.DataFrame, source_label: str) -> dict:
    close = df["Close"]
    volume = df["Volume"]
    macd_line, signal_line = macd(close)

    sig_macd = macd_recently_crossed_up(macd_line, signal_line)
    dist_high = distance_from_52w_high(close)
    sig_near_high = dist_high <= NEAR_HIGH_THRESHOLD
    sig_dma, dma_ratio = fifty_above_two_hundred_dma(close)
    sig_vol, vol_ratio = volume_accumulation(volume)

    score = int(sig_near_high) + int(sig_macd) + int(sig_dma) + int(sig_vol)

    return {
        "ticker": entry["ticker"],
        "symbol": entry["symbol"],
        "name": entry["name"],
        "industry": entry.get("industry", ""),
        "held": bool(entry.get("held", False)),
        "last_close": float(close.iloc[-1]),
        "as_of": close.index[-1].date().isoformat(),
        "source": source_label,
        "score": score,
        "near_52w_high": sig_near_high,
        "dist_52w_high": dist_high,
        "macd_crossover_5d": sig_macd,
        "dma_50_above_200": sig_dma,
        "dma_ratio": dma_ratio,
        "volume_accum": sig_vol,
        "volume_ratio": vol_ratio,
    }


def render_brief(rows: list[dict], run_date: str, freshness: str,
                 warnings: list[str]) -> str:
    rows_sorted = sorted(rows, key=lambda r: (-r["score"], r["dist_52w_high"]))
    held_present = [r for r in rows_sorted if r["held"]]

    # New status-based bucketing (FORMING/READY/TRIGGERED/STALE/WATCHING)
    triggered = [r for r in rows_sorted if not r["held"] and r.get("setup_status") == "TRIGGERED"]
    ready = [r for r in rows_sorted if not r["held"] and r.get("setup_status") == "READY"]
    forming = [r for r in rows_sorted if not r["held"] and r.get("setup_status") == "FORMING"]
    stale = [r for r in rows_sorted if not r["held"] and r.get("setup_status") == "STALE"]
    watching = [r for r in rows_sorted if not r["held"] and r.get("setup_status") == "WATCHING"]

    # Demoted: scored well technically but failed fundamentals gates
    filtered_out = [
        r for r in rows_sorted
        if r["score"] >= FLAG_THRESHOLD and not r.get("passes_gates", True) and not r["held"]
    ]

    new_entrants = [r for r in rows_sorted if r.get("trajectory_tag") == "NEW" and not r["held"]]
    strengthening = [r for r in rows_sorted if r.get("trajectory_tag") == "STRONGER" and not r["held"]]
    has_history = any(r.get("prev_score") is not None for r in rows_sorted)

    lines = [
        f"# Daily Stock Brief — {run_date}",
        "",
        f"**Latest close:** {freshness}",
        "",
        f"_v1 Phase 1a — universe of {len(rows)} (30 picked + held). 4 technical signals + fundamentals gates. Setups classified as TRIGGERED / READY / FORMING / STALE. Trade plans with concrete numbers for actionable setups. Risk: {config.MAX_RISK_PER_TRADE_FRAC*100:.0f}% of ₹{config.SWING_CAPITAL_INR:,} per trade, min R:R {config.MIN_RISK_REWARD_RATIO:.0f}×._",
        "",
    ]

    if not has_history:
        lines.append("> 🌱 **First run with memory** — no prior state available yet. Trajectory tags activate from the next run onward.")
        lines.append("")
    elif new_entrants or strengthening:
        bits = []
        if new_entrants:
            bits.append(f"**🆕 {len(new_entrants)} new entrant{'s' if len(new_entrants)!=1 else ''}**")
        if strengthening:
            bits.append(f"**📈 {len(strengthening)} strengthening**")
        lines.append(f"> {' · '.join(bits)} since the last run.")
        lines.append("")

    for w in warnings:
        lines.append(f"> ⚠️ {w}")
        lines.append("")

    # Held positions section first — always shown so user sees portfolio status
    if held_present:
        lines.extend(["## Your Positions", ""])
        for r in held_present:
            lines.extend(_render_row(r))

    if triggered:
        lines.extend([f"## 🚨 Triggered Today ({len(triggered)}) — newly cleared the bar", ""])
        for r in triggered:
            lines.extend(_render_row(r))

    if ready:
        lines.extend([f"## 🎯 Ready ({len(ready)}) — setup confirmed, plan below", ""])
        for r in ready:
            lines.extend(_render_row(r))

    if not triggered and not ready:
        lines.append(f"## 🎯 Ready (0)\n\n_No setups cleared the bar today. Thin day — see Forming for what's close._\n")

    if forming:
        lines.extend([f"## 🌀 Forming ({len(forming)}) — close to ready, watch conditions", ""])
        for r in forming:
            lines.extend(_render_row(r))

    if stale:
        lines.extend([f"## 🌫️ Stale ({len(stale)}) — was ready, now decaying", ""])
        for r in stale:
            lines.extend(_render_row(r))

    if filtered_out:
        lines.extend([f"## ❌ Filtered out ({len(filtered_out)}) — scored well, failed fundamentals", ""])
        for r in filtered_out:
            reason = r.get("gate_reason") or "—"
            lines.append(f"- `{r['symbol']}` — score {r['score']}/{MAX_SCORE}, **{reason}**")
        lines.append("")

    lines.extend([f"## 👀 Watching ({len(watching)}) — too far to plan, just monitoring", ""])
    if not watching:
        lines.append("_Nothing in the watching bucket today._")
        lines.append("")
    else:
        # Compact format — symbol + 4-signal breakdown to avoid a wall of text
        for r in watching:
            ck = lambda b: "✓" if b else "·"
            tag = r.get("trajectory_tag")
            traj = f" {_TRAJECTORY_ICON[tag]}" if tag else ""
            lines.append(
                f"- `{r['symbol']}`{traj} ({r['industry'][:22]}) — ₹{r['last_close']:.2f} · "
                f"score {r['score']}/{MAX_SCORE} · "
                f"{ck(r['near_52w_high'])}52wh "
                f"{ck(r['macd_crossover_5d'])}MACD "
                f"{ck(r['dma_50_above_200'])}DMA "
                f"{ck(r['volume_accum'])}Vol"
            )
        lines.append("")

    lines.append("---")
    lines.append(f"_Generated {datetime.now(IST).strftime('%Y-%m-%d %H:%M IST')}_")
    return "\n".join(lines)


_TRAJECTORY_ICON = {
    "NEW":      "🆕",
    "STRONGER": "📈",
    "WEAKER":   "📉",
    "STREAK":   "🔥",
}


def _trajectory_line(r: dict) -> str | None:
    tag = r.get("trajectory_tag")
    if tag is None:
        return None
    icon = _TRAJECTORY_ICON.get(tag, "·")
    prev = r.get("prev_score")
    delta = r.get("score_delta")
    streak = r.get("streak_days", 0)

    if tag == "NEW":
        if prev is None:
            return f"- {icon} **Trajectory:** new entrant — no prior history"
        return f"- {icon} **Trajectory:** new entrant — was {prev}/{MAX_SCORE} previously, now {r['score']}/{MAX_SCORE}"
    if tag == "STRONGER":
        return f"- {icon} **Trajectory:** stronger — {delta:+d} vs prior run ({prev}/{MAX_SCORE} → {r['score']}/{MAX_SCORE})"
    if tag == "WEAKER":
        return f"- {icon} **Trajectory:** weaker — {delta:+d} vs prior run ({prev}/{MAX_SCORE} → {r['score']}/{MAX_SCORE})"
    if tag == "STREAK":
        return f"- {icon} **Trajectory:** {streak}-day streak above flag threshold"
    return None


def _render_row(r: dict) -> list[str]:
    chk = lambda b: "✓" if b else "·"
    held_tag = " 🔒 *held*" if r["held"] else ""

    if r.get("dma_ratio") is not None:
        dma_pct = (r["dma_ratio"] - 1) * 100
        dma_label = f"50DMA is {dma_pct:+.1f}% vs 200DMA"
    else:
        dma_label = "50/200 DMA — insufficient history"

    if r.get("volume_ratio") is not None:
        vol_label = f"Last volume {r['volume_ratio']:.2f}× the prior 20-day avg"
    else:
        vol_label = "Volume — insufficient history"

    fund = r.get("fundamentals") or {}
    de = fund.get("debt_to_equity")
    sg = fund.get("sales_growth_ttm_pct")
    if fund:
        de_str = f"{de:.2f}" if de is not None else "—"
        sg_str = f"{sg:+.0f}%" if sg is not None else "—"
        gate_pass = r.get("passes_gates", True)
        gate_mark = "✓" if gate_pass else "✗"
        gate_reason = r.get("gate_reason")
        gate_extra = f" — {gate_reason}" if gate_reason else ""
        fund_line = f"- {gate_mark} **Fundamentals:** D/E {de_str} · sales growth TTM {sg_str}{gate_extra}"
    else:
        fund_line = "- ✗ **Fundamentals:** no Screener data"

    # Title with optional trajectory icon prefix for at-a-glance scanning
    tag = r.get("trajectory_tag")
    title_prefix = f"{_TRAJECTORY_ICON[tag]} " if tag else ""

    status = r.get("setup_status")
    status_badge = ""
    if status == "READY":
        status_badge = " · 🎯 READY"
    elif status == "TRIGGERED":
        status_badge = " · 🚨 TRIGGERED today"
    elif status == "FORMING":
        status_badge = " · 🌀 forming"
    elif status == "STALE":
        status_badge = " · 🌫️ stale"

    out = [
        f"### {title_prefix}{r['symbol']} — {r['name']}{held_tag}{status_badge}",
        f"- *{r['industry']}*",
        f"- **Score:** {r['score']}/{MAX_SCORE} — `{r['ticker']}`",
        f"- **Last close:** ₹{r['last_close']:.2f} ({r['as_of']}, {r['source']})",
        f"- {chk(r['near_52w_high'])} Within 10% of 52w high (currently {r['dist_52w_high'] * 100:.1f}% below)",
        f"- {chk(r['macd_crossover_5d'])} MACD bullish crossover within last 5 sessions",
        f"- {chk(r['dma_50_above_200'])} {dma_label}",
        f"- {chk(r['volume_accum'])} {vol_label}",
        fund_line,
    ]
    traj_line = _trajectory_line(r)
    if traj_line:
        out.append(traj_line)

    out.extend(_announcement_lines(r))
    out.extend(_trade_plan_lines(r))
    out.extend(_watch_conditions_lines(r))
    out.append("")
    return out


def _watch_conditions_lines(r: dict) -> list[str]:
    conds = r.get("watch_conditions")
    if not conds:
        return []
    out = ["", "**Watch conditions** (need ALL for setup to confirm):"]
    for c in conds:
        out.append(f"  - ⏱️ {c}")
    out.append("  → If these clear in the next 3–5 days, a trade plan lands in tomorrow's brief.")
    return out


def _trade_plan_lines(r: dict) -> list[str]:
    plan = r.get("trade_plan")
    if not plan:
        return []

    pos = plan["position"]
    binding = pos["binding_constraint"]

    out = [
        "",
        "**Trade plan** (math, not advice — your call):",
        f"  - **Entry zone:** ₹{plan['entry_zone_low']:.2f} – ₹{plan['entry_zone_high']:.2f}  (current: ₹{plan['current_price']:.2f})",
        f"  - **Stop:** ₹{plan['stop']:.2f}  ({plan['stop_method']})",
        f"  - **Target 1:** ₹{plan['target_1']:.2f}  →  R:R {plan['rr_to_target_1']:.2f}",
        f"  - **Target 2:** ₹{plan['target_2']:.2f}  →  R:R {plan['rr_to_target_2']:.2f}",
        f"  - **Risk per share:** ₹{plan['risk_per_share']:.2f}  (ATR ₹{plan['atr']:.2f}, swing low ₹{plan['swing_low']:.2f})",
    ]

    if plan.get("rr_warning"):
        out.append(f"  - ⚠️ {plan['rr_warning']} — math doesn't justify a full position; consider smaller size or skip")

    if binding == "unfeasible":
        out.append(f"  - ❌ **Position size: 0 shares.** Stock too expensive for ₹{config.PER_SLOT_BUDGET_INR:,.0f} per-slot budget at this stop distance.")
    else:
        binding_note = {
            "risk_budget": f"sized to risk {config.MAX_RISK_PER_TRADE_FRAC*100:.0f}% of capital",
            "slot_budget": f"capped by ₹{config.PER_SLOT_BUDGET_INR:,.0f} per-slot budget — risk would otherwise be smaller",
        }.get(binding, "")
        out.extend([
            f"  - **Position size:** {pos['shares']} share{'s' if pos['shares']!=1 else ''}  ({binding_note})",
            f"     - Capital deployed: ₹{pos['capital_deployed_inr']:,.2f}  ({pos['capital_deployed_inr']/config.SWING_CAPITAL_INR*100:.1f}% of swing capital)",
            f"     - Max loss if stop hits: **₹{pos['max_loss_inr']:,.2f}** ({pos['max_loss_pct_of_capital']:.2f}% of capital)",
            f"     - Profit at T1: ₹{pos['expected_profit_t1_inr']:,.2f} (+{pos['expected_return_t1_pct_of_capital']:.2f}% of capital)",
            f"     - Profit at T2: ₹{pos['expected_profit_t2_inr']:,.2f} (+{pos['expected_return_t2_pct_of_capital']:.2f}% of capital)",
        ])
        if pos['ideal_shares'] != pos['shares'] and binding == "slot_budget":
            out.append(f"     - _Note: ideal sizing would be {pos['ideal_shares']} shares (₹{pos['ideal_shares']*plan['current_price']:,.0f}) but per-slot budget caps at {pos['shares']}._")

    return out


def _announcement_lines(r: dict, top_n: int = 5) -> list[str]:
    anns = r.get("announcements")
    attempted = r.get("announcements_attempted", False)
    if not attempted:
        return []  # didn't try — silent (e.g., plain watching stocks)
    if anns is None:
        return ["- 📰 **Recent announcements:** _fetch failed_"]
    if not anns:
        return ["- 📰 **Recent announcements (30d):** _none filed_"]

    out = [f"- 📰 **Recent announcements ({len(anns)} in last 30d, top {min(top_n, len(anns))}):**"]
    for a in anns[:top_n]:
        cat = categorize(a)
        label = CATEGORY_LABEL.get(cat, cat)
        # Date is "DD-MMM-YYYY HH:MM:SS" — keep just date for readability
        date_str = (a.get("date") or "").split(" ")[0]
        # Truncate long category descriptions
        title = (a.get("category") or "").strip()
        if len(title) > 70:
            title = title[:67] + "…"
        out.append(f"    - `{date_str}` {label} — {title}")
    return out


